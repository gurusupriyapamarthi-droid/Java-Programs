package com.oops.encapsulation;

public class Student {
	private int sid;
	private String sname;
	private int age;
	
	public void setSid(int sid) {
		this.sid=sid;
	}
	public int getSid() {
		return sid;
	}
	public void setSname(String sname) {
		this.sname=sname;
	}
	public String getSname() {
		return sname;
	}
	public void setAge(int age) {
		this.age=age;
	}
	public int getAge() {
		return age;
	}



}
